create table employee (
    id              bigint generated by default as identity primary key,
    employee_code   varchar(20)    not null,
    full_name       varchar(200)   not null,
    email           varchar(254)   not null,
    job_title       varchar(100)   not null,
    department      varchar(100)   not null,
    country_code    varchar(2)     not null,
    currency        varchar(3)     not null,
    salary          numeric(14, 2) not null,
    employment_type varchar(20)    not null,
    hire_date       date           not null,
    created_at      timestamptz    not null default now(),
    updated_at      timestamptz    not null default now(),
    constraint uk_employee_code unique (employee_code),
    constraint ck_employee_salary_positive check (salary > 0),
    constraint ck_employee_employment_type check (employment_type in ('FULL_TIME', 'PART_TIME', 'CONTRACTOR'))
);

-- Emails are unique regardless of case.
create unique index uk_employee_email on employee (lower(email));

-- Serves filters on country alone (leading column) and on country + job title.
create index ix_employee_country_job_title on employee (country_code, job_title);

create index ix_employee_department on employee (department);
